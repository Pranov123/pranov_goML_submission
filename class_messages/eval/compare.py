"""Compare local models, with and without the code-side guardrails, on all three message sets.

    python eval/compare.py --models qwen2.5:3b llama3.2:3b --out eval/results.md

"pipeline" = extract.py as submitted. "raw model" = the same prompt and JSON schema, but no injection
stripping and no validation: whatever the model returns is written out. Each model is warmed up first,
so the timings don't include loading it.
"""
import argparse
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import extract as E  # noqa: E402
from score import score  # noqa: E402

SETS = [("practice", HERE.parent / "messages", HERE / "practice_expected.json"),
        ("dev (tuned on)", HERE / "devset", HERE / "devset_expected.json"),
        ("held-out", HERE / "heldout", HERE / "heldout_expected.json")]


def run(inbox, model, guarded, usage):
    tasks, problems = [], []
    for path in sorted(inbox.glob("*.txt")):
        try:
            if guarded:
                tasks += E.extract_one(path, E.DEFAULT_HOST, model, usage)
            else:
                mid, body = E.parse_message(path)
                raw = E.call_model(E.DEFAULT_HOST, model, body, usage)
                tasks += [{"message_id": mid, "task": t.get("task", ""), "owner": t.get("owner"), "due": t.get("due")}
                          for t in raw.get("tasks", []) if isinstance(t, dict)]
        except Exception as e:
            problems.append(f"{path.name}: {type(e).__name__}")
    return tasks, problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", nargs="+", required=True)
    ap.add_argument("--out", default=str(HERE / "results.md"))
    args = ap.parse_args()

    rows = []
    for model in args.models:
        E.call_model(E.DEFAULT_HOST, model, "warm-up", {"prompt_tokens": 0, "output_tokens": 0, "calls": 0})
        for guarded in (True, False):
            for name, inbox, expected in SETS:
                usage = {"prompt_tokens": 0, "output_tokens": 0, "calls": 0}
                start = time.time()
                tasks, errors = run(inbox, model, guarded, usage)
                secs = time.time() - start
                m, _ = score(tasks, json.loads(expected.read_text(encoding="utf-8"))["tasks"], inbox)
                row = {"model": model, "mode": "pipeline" if guarded else "raw model", "set": name, **m,
                       "sec_per_msg": round(secs / max(usage["calls"], 1), 1), "errors": len(errors)}
                rows.append(row)
                print(json.dumps(row), flush=True)

    cols = ["model", "mode", "set", "task_precision", "task_recall", "owner_accuracy", "due_accuracy",
            "invented_owner_or_due", "extra", "missed", "sec_per_msg"]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    Path(args.out).write_text("# Model comparison\n\nGenerated by `eval/compare.py`.\n\n" + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
